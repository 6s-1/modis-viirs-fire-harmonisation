"""Canada boundary for the live-fire Worker's point-in-polygon filter.

Same source as the harmonised data's Canada mask (export.canada_cells): Natural Earth 1:50m
admin-1, Canada, dissolved. Simplified (~TOL degrees) to keep the Worker small; each polygon
carries its bounding box so most points are rejected or accepted cheaply.

Output: worker/src/canada.js  (export const CANADA_POLYGONS = [{ bbox, rings }])
"""
from __future__ import annotations

import json

import geopandas as gpd

import config as C

TOL = 0.01  # degrees (~1 km); keeps the border accurate to about a kilometre


def main() -> None:
    prov = gpd.read_file(C.DATA / "external" / "ne_admin1" / "ne_50m_admin_1_states_provinces.shp")
    g = prov[prov.admin == "Canada"].to_crs("EPSG:4326").dissolve().geometry.iloc[0]
    g = g.simplify(TOL, preserve_topology=True)
    polys = []
    for p in getattr(g, "geoms", [g]):
        if p.area < 0.002:  # drop specks (tiny islets) that only add size
            continue
        rings = [[[round(x, 4), round(y, 4)] for x, y in p.exterior.coords]]
        rings += [[[round(x, 4), round(y, 4)] for x, y in r.coords] for r in p.interiors]
        minx, miny, maxx, maxy = p.bounds
        polys.append({"bbox": [round(minx, 4), round(miny, 4), round(maxx, 4), round(maxy, 4)], "rings": rings})
    out = C.REPO / "worker" / "src" / "canada.js"
    out.write_text("// Generated by pipeline/canada_boundary.py from Natural Earth 1:50m admin-1 (Canada), the same\n"
                   "// boundary as the harmonised data's Canada mask. Do not edit by hand.\n"
                   f"export const CANADA_POLYGONS = {json.dumps(polys, separators=(',', ':'))};\n")
    n = sum(len(r) for p in polys for r in p["rings"])
    print(f"{len(polys)} polygons, {n:,} vertices, {out.stat().st_size / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
